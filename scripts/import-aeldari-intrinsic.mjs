import {createHash} from 'node:crypto';
import {writeFileSync} from 'node:fs';
import {loadExport} from './import-wahapedia-11e.mjs';

const [directory,destination]=process.argv.slice(2);
if(!destination)throw Error('Usage: node scripts/import-aeldari-intrinsic.mjs CSV_DIR OUTPUT_TS');
const {tables}=await loadExport({directory});
const sheets=tables.Datasheets.filter(s=>s.faction_id==='AE'&&['000000186','000000367'].includes(s.source_id));
if(sheets.length!==76)throw Error('Review current matched-play Aeldari inventory');
const data=Object.fromEntries(sheets.map(s=>[s.name,tables.Datasheets_abilities.filter(a=>a.datasheet_id===s.id&&!['Core','Faction'].includes(a.type)).map(a=>{
 const rule=a.ability_id?tables.Abilities.find(x=>x.id===a.ability_id):a;
 if(!rule?.name)throw Error('Unnamed intrinsic ability on '+s.name);
 return {name:rule.name,type:a.type,source:s.link,sourceHash:createHash('sha256').update(JSON.stringify(a)).digest('hex')};
})]).sort(([a],[b])=>a.localeCompare(b,'en')));
if(Object.values(data).flat().length!==159)throw Error('Review the named intrinsic ability inventory');
writeFileSync(destination,'// Generated by scripts/import-aeldari-intrinsic.mjs from the current 11e export.\n'+
 '// Source names and hashes audit executable reminders; raw source text is not rendered as fallback rules.\n'+
 'export const AELDARI_INTRINSIC_INVENTORY:Readonly<Record<string,readonly {name:string;type:string;source:string;sourceHash:string}[]>>='+JSON.stringify(data,null,1)+';\n');
