const plain=s=>s.replace(/<[^>]+>/g,' ').replace(/&nbsp;/gi,' ').replace(/\s+/g,' ').trim();
const key=s=>s.toLowerCase().replaceAll('’',"'").replaceAll('‑','-');
function removeItems(base,items){
 const result=[...base];
 for(const item of items){
  const i=result.indexOf(item);
  if(i<0)throw Error('Unknown replacement or insufficient copies of '+item);
  result.splice(i,1);
 }
 return result;
}
export function parseCustodesKit({unit,loadout,options,composition,knownItems}){
 const match=plain(loadout).match(/^(?:This|Every) model is equipped with: (.+)\.$/);
 const modelCounts=composition.match(/^(\d+)(?:[-–](\d+))?\s+/);
 if(!match||!modelCounts)throw Error(unit+' has unrecognized model equipment or composition');
 const items=text=>plain(text).replace(/\.$/,'').split(/; |, | and /).flatMap(entry=>{
  const m=entry.match(/^(?:(\d+) )?(.+)$/);
  if(!m||!knownItems.has(key(m[2])))throw Error(unit+' unknown equipment '+entry);
  return Array(Number(m[1]??1)).fill(m[2]);
 });
 const base=items(match[1]), variants=[base], replacedSets=[], optional=[];
 for(const option of options){
  const add=plain(option).match(/^(?:This model|1 model) can be equipped with (.+)\.$/);
  if(add){const extra=items(add[1]);if(extra.length!==1)throw Error(unit+' unsupported optional bundle');optional.push(extra[0]);continue;}
  const swap=plain(option).match(/^(?:This model’s |All models in this unit can each have their )(.+?) (?:can be replaced|replaced) with (.+)$/);
  if(!swap)throw Error(unit+' unsupported replacement: '+option);
  const removed=items(swap[1]),retained=removeItems(base,removed);
  // Only overlapping substitutions can share one set of mutually exclusive alternatives.
  if(replacedSets.some(set=>!set.some(item=>removed.includes(item))))throw Error(unit+' gained an independent weapon selection');
  replacedSets.push(removed);
  const list=Array.from(option.matchAll(/<li>(.*?)<\/li>/g),entry=>entry[1]);
  for(const choice of list.length?list:[swap[2]])variants.push([...retained,...items(choice)]);
 }
 // Extract the multiset intersection so permanent equipment is printed just once.
 const remaining=variants.map(v=>[...v]), fixed=[];
 for(const item of base){
  if(remaining.every(v=>v.includes(item))){fixed.push(item);for(const v of remaining)v.splice(v.indexOf(item),1);}
 }
 return {unit,min:Number(modelCounts[1]),max:Number(modelCounts[2]??modelCounts[1]),fixed,choices:variants.length>1?remaining:[],optional};
}
export function custodesKits(tables,manual){
 if(manual.slug!=='adeptus-custodes'||!manual.version)throw Error('Expected a dated Custodes Field Manual');
 const sources=new Map(tables.Source.map(s=>[s.id,s]));
 const sheets=tables.Datasheets.filter(d=>d.faction_id==='AC'&&!sources.get(d.source_id)?.name.includes('Legends'));
 const manualNames=new Set(manual.units.filter(d=>!d.legends).map(r=>key(r.name)));
 if(manualNames.size!==sheets.length||sheets.some(d=>!manualNames.has(key(d.name))))throw Error('Custodes inventory differs between CSV and MFM');
 return sheets.map(d=>{
  const own=n=>tables[n].filter(r=>r.datasheet_id===d.id);
  const compositions=own('Datasheets_unit_composition');
  if(compositions.length!==1||!d.link.startsWith('https://wahapedia.ru/wh40k11ed/factions/adeptus-custodes/'))throw Error(d.name+' has unsupported model types or edition');
  const knownItems=new Set([...own('Datasheets_wargear').map(w=>w.name.split(/\s+[–—-]\s+/)[0]),...own('Datasheets_abilities').filter(a=>a.type==='Wargear').map(a=>a.name)].map(key));
  const kit=parseCustodesKit({unit:d.name,loadout:d.loadout,options:own('Datasheets_options').map(r=>r.description),composition:plain(compositions[0].description),knownItems});
  return {...kit,ranged:[...new Set(own('Datasheets_wargear').filter(w=>w.type==='Ranged').map(w=>w.name.split(/\s+[–—-]\s+/)[0]))]};
 }).sort((a,b)=>a.unit.localeCompare(b.unit,'en'));
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const [directory,mfmPath,output]=process.argv.slice(2);
 if(!output)throw Error('Usage: node scripts/import-custodes-loadouts.mjs CSV_DIR CUSTODES_MFM_YAML OUTPUT_TS');
 const {tables}=await loadExport({directory});
 const kits=custodesKits(tables,parse(readFileSync(mfmPath,'utf8')));
 writeFileSync(output,'// Generated by scripts/import-custodes-loadouts.mjs.\nexport const CUSTODES_KITS='+JSON.stringify(kits,null,2)+' as const;\n');
}
