import {readFileSync,writeFileSync} from 'node:fs';
import {parse} from 'yaml';
import {loadExport} from './import-wahapedia-11e.mjs';

const [directory,manualFile,output]=process.argv.slice(2);
if(!output)throw Error('Usage: node scripts/import-final-day-loadouts.mjs CSV_DIR TYRANIDS_MFM_YAML OUTPUT_TS');
const manual=parse(readFileSync(manualFile,'utf8'));
if(manual.slug!=='tyranids'||!manual.version)throw Error('Expected a dated Tyranids Field Manual');
const {tables}=await loadExport({directory});
const key=value=>value.toLowerCase().replaceAll('’',"'");
const text=value=>value.replace(/<[^>]+>/g,' ').replace(/\s+/g,' ').trim();
const nativeNames=new Set(manual.units.filter(u=>!u.legends&&!u.groupTitle).map(u=>key(u.name)));
const rows=[];
for(const card of tables.Datasheets.filter(s=>s.faction_id==='TYR').sort((a,b)=>a.name.localeCompare(b.name,'en'))){
 const own=t=>tables[t].filter(r=>r.datasheet_id===card.id);
 const keywords=new Set(own('Datasheets_keywords').map(w=>w.keyword.toUpperCase()));
 if(!nativeNames.has(key(card.name))||!keywords.has('VANGUARD INVADER')||['AIRCRAFT','BROODLORD','GENESTEALERS'].some(k=>keywords.has(k)))continue;
 const proxy=tables.Datasheets.find(s=>s.faction_id==='GC'&&s.name===card.name);
 if(!proxy||!card.link.startsWith('https://wahapedia.ru/wh40k11ed/factions/tyranids/'))throw Error('Missing current allied datasheet for '+card.name);
 const weapons=own('Datasheets_wargear').map(w=>({name:w.name.trim(),phase:w.type==='Ranged'?'Shooting':'Fight',abilities:w.description?w.description.split(/,\s*/):[]}));
 const weaponNames=new Map(weapons.map(w=>[key(w.name),w.name]));
 const equipment=raw=>text(raw).split(/; |, /).map(item=>{
  const name=weaponNames.get(key(item.replace(/^1 /,'')));
  if(!name)throw Error(card.name+' unknown equipment '+item);
  return name;
 });
 const fixed=[];
 for(const clause of text(card.loadout).matchAll(/(This model|Every model|The [^.]+?|\d+ [^.]+?) (?:is|are) equipped with: ([^.]*)\./g)){
  const prefix=clause[1],items=equipment(clause[2]);
  // Mixed Raveners specify a single venom bolt, alongside the Prime and
  // three other heavily armed bodies. Counts are per group, not per unit model.
  const m=prefix.match(/^(\d+) /);
  fixed.push({count:prefix==='Every model'?'each':m?Number(m[1]):1,items});
 }
 if(!fixed.length)throw Error('Missing standard equipment for '+card.name);
 const variants=[];
 for(const r of own('Datasheets_options')){
  if(/^none\.?$/i.test(text(r.description)))continue;
  const stem=r.description.match(/^This model’s (.+?) can be replaced with one of the following:/);
  const choices=[...r.description.matchAll(/<li>(.*?)<\/li>/g)].map(match=>equipment(match[1]));
  if(!stem||!choices.length)throw Error('Review new Final Day weapon option: '+r.description);
  variants.push({standard:equipment(stem[1]),choices});
 }
 rows.push({unit:card.name,source:card.link,fixed,variants,weapons});
}
if(rows.length!==14)throw Error('Review changed Final Day allied eligibility');
writeFileSync(output,'// Generated by scripts/import-final-day-loadouts.mjs from current 11e native and allied cards.\nexport const FINAL_DAY_KITS=[\n'+rows.map(r=>'  '+JSON.stringify(r)).join(',\n')+'\n] as const;\n');
