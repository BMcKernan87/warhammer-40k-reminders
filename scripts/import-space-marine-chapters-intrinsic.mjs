import {createHash} from 'node:crypto';
import {writeFileSync} from 'node:fs';
import {loadExport} from './import-wahapedia-11e.mjs';
import {CHAPTER_SPECS} from './import-space-marine-chapters-relational.mjs';

const [directory,destination]=process.argv.slice(2);
if(!destination)throw Error('Usage: node scripts/import-space-marine-chapters-intrinsic.mjs CSV_DIR OUTPUT_TS');
const {tables}=await loadExport({directory}),inventory={};
for(const spec of CHAPTER_SPECS){
 const source=tables.Source.find(s=>s.id===spec.sourceId);
 if(!source||source.edition!=='11')throw Error('Review chapter source '+spec.faction);
 const sheets=tables.Datasheets.filter(s=>s.faction_id==='SM'&&s.source_id===spec.sourceId);
 if(sheets.length!==spec.cards)throw Error('Review chapter card inventory '+spec.faction);
 inventory[spec.faction]=Object.fromEntries(sheets.map(s=>[s.name,tables.Datasheets_abilities.filter(a=>a.datasheet_id===s.id&&!['Core','Faction'].includes(a.type)).map(a=>{
  const rule=a.ability_id?tables.Abilities.find(x=>x.id===a.ability_id):a;
  if(!rule?.name)throw Error('Unnamed chapter ability '+spec.faction+' / '+s.name);
  return {name:rule.name,type:a.type,source:s.link,sourceHash:createHash('sha256').update(JSON.stringify(a)).digest('hex')};
 })]).sort(([a],[b])=>a.localeCompare(b,'en')));
}
if(Object.values(inventory).flatMap(f=>Object.values(f).flat()).length!==151)throw Error('Review the named chapter intrinsic inventory');
writeFileSync(destination,'// Generated by scripts/import-space-marine-chapters-intrinsic.mjs from the current 11e export.\n'+
 '// Faction keys preserve the six Black Templars vehicle name collisions. Every named entry has explicit runtime handling or named delegation.\n'+
 'export const CHAPTER_INTRINSIC_INVENTORY:Readonly<Record<string,Readonly<Record<string,readonly {name:string;type:string;source:string;sourceHash:string}[]>>>>='+JSON.stringify(inventory,null,1)+';\n');
