import {readFileSync,writeFileSync} from 'node:fs';
import {isDeepStrictEqual} from 'node:util';
import {parse} from 'yaml';
import {loadExport,modelProfile,rosterMetadata} from './import-wahapedia-11e.mjs';
import {readPrices} from './import-imperial-knights.mjs';

const [directory,manualFile,output]=process.argv.slice(2);
if(!output)throw Error('Usage: node scripts/import-custodes.mjs CSV_DIR CUSTODES_MFM_YAML OUTPUT_TS');
const {tables}=await loadExport({directory});
const manual=parse(readFileSync(manualFile,'utf8'));
if(manual.slug!=='adeptus-custodes'||!manual.version)throw Error('Missing Custodes MFM');
const normal=name=>name.toLowerCase().replaceAll('‑','-').replace(/[’‘]/g,"'").trim();
const pack='https://assets.warhammer-community.com/eng_30-09_wh40k_faction_pack_adeptus_custodes-xlscee8b1b-b1evo9u920.pdf';
const native=tables.Datasheets.filter(d=>d.faction_id==='AC'&&!tables.Source.find(s=>s.id===d.source_id)?.name.includes('Legends'));
const priced=manual.units.filter(u=>!u.legends);
const prices=new Map(priced.map(u=>[normal(u.name),u]));
const names=new Map(native.map(d=>[normal(d.name),d.name]));
if(prices.size!==priced.length||names.size!==native.length||names.size!==prices.size)throw Error('Source inventories disagree');
const sheets=native.map(d=>{
 const price=prices.get(normal(d.name));
 const source=tables.Source.find(s=>s.id===d.source_id);
 // Both aircraft appear in the September pack, pp. 32–35. The export links
 // their profiles to a shared Forge World source with a zero edition marker.
 const packAircraft=source?.name==='Adeptus Custodes (Forge World)'&&source.edition==='0'&&['Orion Assault Dropship','Ares Gunship'].includes(d.name);
 if(!price||(!packAircraft&&(source?.edition!=='11'||source.name!=='Adeptus Custodes'||source.type!=='App'))||!d.link.startsWith('https://wahapedia.ru/wh40k11ed/factions/adeptus-custodes/'))throw Error('Missing 11e source or matched-play price for '+d.name);
 const own=key=>tables[key].filter(s=>s.datasheet_id===d.id);
 const costs=readPrices(own('Datasheets_models_cost'),d.name,price);
 const data=rosterMetadata(tables,d.name,d.id);
 // The faction index also tags Sisters as ADEPTUS CUSTODES. The card and the
 // Anathema Psykana army rule specify that Sisters do not have that keyword.
 if(data.keywords.includes('ANATHEMA PSYKANA'))data.keywords=data.keywords.filter(k=>k!=='ADEPTUS CUSTODES');
 if(!data.keywords.includes('ADEPTUS CUSTODES')&&!data.keywords.includes('ANATHEMA PSYKANA'))throw Error(d.name+' has no supported faction keyword');
 const min=data.composition.reduce((sum,m)=>sum+m.min,0),max=data.composition.reduce((sum,m)=>sum+m.max,0);
 if(min!==costs.sizes[0]||max!==costs.sizes.at(-1))throw Error(d.name+' composition differs from MFM');
 const models=own('Datasheets_models');
 if(!models.length||new Set(models.map(m=>m.name)).size!==models.length)throw Error(d.name+' duplicate or missing profiles');
 const profiles=models.length===1?{profile:modelProfile(models[0],d.name)}:{modelProfiles:Object.fromEntries(models.map(m=>[m.name,modelProfile(m,d.name)]))};
 const edges=new Set(tables.Datasheets_leader.filter(l=>l.leader_id===d.id).map(l=>l.attached_id));
 const bodyguards=native.filter(b=>edges.has(b.id)).map(b=>b.name).sort();
 const manualBodies=(price.supportTo??price.leaderTo??[]).map(n=>names.get(normal(n))).filter(Boolean).sort();
 if(!isDeepStrictEqual(bodyguards,manualBodies)||(d.is_support==='true')!==!!price.supportTo)throw Error(d.name+' source attachment disagreement');
 const attachment=bodyguards.length?{attachmentRole:d.is_support==='true'?'support':'leader',bodyguards}:{};
 return {faction:'Adeptus Custodes',unit:d.name,source:d.link,pointsSource:'https://mfm.warhammer-community.com/en/adeptus-custodes',verified:'sizes-and-points',...costs,...data,...profiles,...attachment};
}).sort((a,b)=>a.unit<b.unit?-1:1);
writeFileSync(output,"// Generated by scripts/import-custodes.mjs.\nimport type {Datasheet2026} from './datasheets-2026';\n"+
 'export const CUSTODES_REVISION='+JSON.stringify({pack,mfmVersion:manual.version,exportRevision:tables.Last_update[0].last_update})+' as const;\n'+
 'export const CUSTODES_SHEETS:readonly Datasheet2026[]='+JSON.stringify(sheets,null,2)+';\n');
