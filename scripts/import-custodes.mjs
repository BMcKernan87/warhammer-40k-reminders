import {readFileSync,writeFileSync} from 'node:fs';
import {parse} from 'yaml';
import {loadExport} from './import-wahapedia-11e.mjs';
import {importNativeMuster} from './import-native-muster.mjs';

const [directory,manualFile,output]=process.argv.slice(2);
if(!output)throw Error('Usage: node scripts/import-custodes.mjs CSV_DIR CUSTODES_MFM_YAML OUTPUT_TS');
const {tables}=await loadExport({directory});
const manual=parse(readFileSync(manualFile,'utf8'));
const pack='https://assets.warhammer-community.com/eng_30-09_wh40k_faction_pack_adeptus_custodes-xlscee8b1b-b1evo9u920.pdf';
// These aircraft are confirmed by the 11th-edition publisher pack pp. 32–35.
const spec={name:'Adeptus Custodes',slug:'adeptus-custodes',factionId:'AC',packAircraftOrModels:['Orion Assault Dropship','Ares Gunship']};
const sheets=importNativeMuster(tables,manual,spec);
for(const sheet of sheets){
 // The index groups the Sisterhood under Custodes, although their printed faction keyword is Anathema Psykana only.
 if(sheet.keywords.includes('ANATHEMA PSYKANA'))sheet.keywords=sheet.keywords.filter(k=>k!=='ADEPTUS CUSTODES');
 if(!sheet.keywords.includes('ANATHEMA PSYKANA')&&!sheet.keywords.includes('ADEPTUS CUSTODES'))throw Error(sheet.unit+' lacks its printed faction keyword');
}
writeFileSync(output,"// Generated by scripts/import-custodes.mjs.\nimport type {Datasheet2026} from './datasheets-2026';\n"+
 'export const CUSTODES_REVISION='+JSON.stringify({pack,mfmVersion:manual.version,exportRevision:tables.Last_update[0].last_update})+' as const;\n'+
 'export const CUSTODES_SHEETS:readonly Datasheet2026[]='+JSON.stringify(sheets,null,2)+';\n');
