import {readFileSync,writeFileSync} from 'node:fs';
import {parse} from 'yaml';
import {loadExport,modelProfile,rosterMetadata} from './import-wahapedia-11e.mjs';
import {readPrices} from './import-imperial-knights.mjs';
import {isDeepStrictEqual} from 'node:util';

const normal=name=>name.toLowerCase().replaceAll('’',"'").trim();
const [directory,manualPath,output]=process.argv.slice(2);
if(!output)throw Error('Usage: node scripts/import-shadow-legion.mjs CSV_DIR CHAOS_SPACE_MARINES_MFM_YAML OUTPUT_TS');
const {tables}=await loadExport({directory});
const manual=parse(readFileSync(manualPath,'utf8'));
if(manual.slug!=='chaos-space-marines'||!manual.version)throw Error('Unexpected MFM');
const sources=tables.Source.filter(s=>s.name==='Chaos Space Marines'&&s.edition==='11'&&s.version);
if(sources.length!==1)throw Error('Missing 11th edition source');
const inSource=tables.Datasheets.filter(s=>s.source_id===sources[0].id);
const marineSheets=inSource.filter(s=>s.faction_id==='CSM');
const shadowSheets=inSource.filter(s=>s.faction_id==='CD');
const explicit=['Chaos Lord','Chaos Lord In Terminator Armour','Chaos Lord with Jump Pack','Chaos Terminator Squad','Chosen','Dark Apostle','Havocs','Legionaries','Master Of Possession','Possessed','Raptors','Sorcerer','Sorcerer In Terminator Armour','Warp Talons'];
const damned=new Set(tables.Datasheets_keywords.filter(k=>k.keyword.toUpperCase()==='DAMNED').map(k=>k.datasheet_id));
const allowed=marineSheets.filter(s=>explicit.includes(s.name)||damned.has(s.id));
const uniqueNames=rows=>rows.map(s=>s.name).sort();
if(!isDeepStrictEqual(uniqueNames(allowed),uniqueNames(shadowSheets)))throw Error('Shadow Legion proxy inventory disagrees with Thralls of the First Prince');
const priced=new Map(manual.units.filter(s=>!s.legends).map(u=>[normal(u.name),u]));
const sheets=allowed.map(d=>{
 const price=priced.get(normal(d.name));
 if(!price)throw Error(d.name+' missing in MFM');
 const own=table=>tables[table].filter(r=>r.datasheet_id===d.id);
 const data=rosterMetadata(tables,d.name,d.id);
 if(!data.keywords.includes('HERETIC ASTARTES'))throw Error(d.name+' lacks allied faction keyword');
 const costs=readPrices(own('Datasheets_models_cost'),d.name,price);
 const proxy=shadowSheets.find(s=>s.name===d.name);
 const proxyPrices=tables.Datasheets_models_cost.filter(s=>s.datasheet_id===proxy.id);
 if(!isDeepStrictEqual(costs,readPrices(proxyPrices,d.name,price)))throw Error(d.name+' Shadow Legion price mismatch');
 const min=data.composition.reduce((total,s)=>total+s.min,0),max=data.composition.reduce((total,s)=>total+s.max,0);
 if(costs.sizes[0]!==min||costs.sizes.at(-1)!==max)throw Error(d.name+' MFM composition mismatch');
 const models=own('Datasheets_models');
 if(!models.length||models.length!==new Set(models.map(m=>m.name)).size)throw Error(d.name+' missing or duplicate profiles');
 const profiles=models.length===1?{profile:modelProfile(models[0],d.name)}:{modelProfiles:Object.fromEntries(models.map(m=>[m.name,modelProfile(m,d.name)]))};
 const edges=new Set(tables.Datasheets_leader.filter(l=>l.leader_id===d.id).map(l=>l.attached_id));
 const bodyguards=allowed.filter(b=>edges.has(b.id)).map(b=>b.name).sort();
 const permitted=(price.supportTo??price.leaderTo??[]).map(n=>allowed.find(s=>normal(s.name)===normal(n))?.name).filter(Boolean).sort();
 if(!isDeepStrictEqual(bodyguards,permitted)||(d.is_support==='true')!==!!price.supportTo)throw Error(d.name+' MFM attachment disagreement');
 const attachment=bodyguards.length?{attachmentRole:d.is_support==='true'?'support':'leader',bodyguards}:{};
 return {faction:'Chaos Daemons',unit:d.name,source:d.link,pointsSource:'https://mfm.warhammer-community.com/en/chaos-space-marines',verified:'sizes-and-points',...costs,...data,...profiles,...attachment};
}).sort((a,b)=>a.unit<b.unit?-1:1);
writeFileSync(output,"// Generated by scripts/import-shadow-legion.mjs.\nimport type {Datasheet2026} from './datasheets-2026';\nexport const SHADOW_LEGION_SHEETS:readonly Datasheet2026[]="+JSON.stringify(sheets,null,2)+';\n');
