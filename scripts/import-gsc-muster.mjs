import {readFileSync,writeFileSync} from 'node:fs';
import {parse} from 'yaml';
import {loadExport} from './import-wahapedia-11e.mjs';
import {importNativeMuster} from './import-native-muster.mjs';
import {applyModelComposition} from './import-mfm-composition.mjs';

const [dir,mfmPath,unitPath,compPath,out]=process.argv.slice(2);
if (!out) throw Error('Usage: node scripts/import-gsc-muster.mjs CSV_DIR MFM_YAML UNITS_JSON COMPOSITIONS_JSON OUTPUT_TS');
const {tables}=await loadExport({directory:dir});
const manual=parse(readFileSync(mfmPath,'utf8'));
const faction='Genestealer Cults';
const nativeIds=new Set(tables.Source.filter(s=>s.name===faction&&s.edition==='11').map(s=>s.id));
// The GC index also lists borrowed Militarum and Tyranid units. Their own
// current cards determine the allied pool; only native entries use these costs.
const nativeTables={...tables,Datasheets:tables.Datasheets.filter(r=>nativeIds.has(r.source_id))};
const jackals=nativeTables.Datasheets.find(d=>d.name==='Atalan Jackals');
if(!jackals)throw Error('Missing Atalan Jackals');
const nine=tables.Datasheets_models_cost.filter(row=>row.datasheet_id===jackals.id&&row.description.trim()==='9 models');
const bands=manual.units.find(u=>u.name==='Atalan Jackals')?.pricing;
const published=bands?.map(group=>group.costs.find(c=>c.models===9)?.points);
if(manual.version!=='1.6'||published?.join()!=='160,170'||nine.length!==2)throw Error('Review the Atalan Jackals pricing discrepancy');
const corrections=new Map();
nine.forEach((row,i)=>{
  // The separately published v1.6 table also displays these nine-model prices:
  // https://praetorium.gg/factions/genestealer-cults/rules/mfm-1-6/datasheets/atalan-jackals
  // Limit the exception to the two observed mismatches, preserving all other checks.
  if(Number(row.cost)===published[i])return;
  if(Number(row.cost)!==published[i]-10)throw Error('New Atalan Jackals source discrepancy');
  corrections.set(row,{...row,cost:String(published[i])});
});
nativeTables.Datasheets_models_cost=tables.Datasheets_models_cost.map(r=>corrections.get(r)??r);
const sheets=importNativeMuster(nativeTables,manual,{name:faction,slug:'genestealer-cults',factionId:'GC',packAircraftOrModels:[]});
if(corrections.size){
 const sheet=sheets.find(s=>s.unit==='Atalan Jackals');
 sheet.priceNotesBySize={9:'Uses the October MFM v1.6 nine-model bracket. The November datasheet export lists this bracket 10 points lower.'};
}
const json=path=>JSON.parse(readFileSync(path,'utf8'));
applyModelComposition(sheets,json(unitPath),json(compPath),manual.slug,manual.firstSeen);
if(sheets.length!==24)throw Error('Reconcile the current matched-play Cult inventory');
writeFileSync(out,"// Generated by scripts/import-gsc-muster.mjs.\nimport type {Datasheet2026} from './datasheets-2026';\n"+
  'export const GSC_REVISION='+JSON.stringify({manual:manual.version,exportUpdated:tables.Last_update[0].last_update,
    composition:'https://github.com/wn-mitch/40kdc-data/tree/fd1035a4e2ac7330835010e660bdd7216bfa3fd9/data/core/genestealer-cults'})+' as const;\n'+
  'export const GSC_SHEETS:readonly Datasheet2026[]='+JSON.stringify(sheets,null,2)+';\n');
