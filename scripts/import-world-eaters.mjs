import {readFileSync,writeFileSync} from 'node:fs';
import {parse} from 'yaml';
import {loadExport} from './import-wahapedia-11e.mjs';
import {importNativeMuster} from './import-native-muster.mjs';
import {applyModelComposition} from './import-mfm-composition.mjs';

const [directory,manualPath,unitsPath,compositionPath,destination]=process.argv.slice(2);
if(!destination)throw Error('Usage: node scripts/import-world-eaters.mjs CSV_DIR MFM_YAML UNITS_JSON COMPOSITIONS_JSON OUTPUT_TS');
const {tables}=await loadExport({directory});
const manual=parse(readFileSync(manualPath,'utf8'));
// The export encodes a second, empty faction-keyword slot on these app cards.
// Discard only that placeholder after checking the actual scoped faction keyword.
const native=tables.Datasheets.filter(s=>s.faction_id==='WE'&&s.source_id==='000000210');
const empty=new Set(native.flatMap(sheet=>{
 const keywords=tables.Datasheets_keywords.filter(k=>k.datasheet_id===sheet.id);
 const actual=keywords.filter(k=>k.is_faction_keyword==='true'&&k.keyword);
 if(actual.length!==1||!['World Eaters','Blood Legions'].includes(actual[0].keyword))throw Error('Unrecognized World Eaters faction keyword for '+sheet.name);
 return keywords.filter(k=>k.is_faction_keyword==='true'&&!k.keyword&&!k.model);
}));
const jakhals=native.find(s=>s.name==='Jakhals');
const rows=tables.Datasheets_unit_composition.filter(c=>c.datasheet_id===jakhals.id);
if(rows.map(c=>c.description).join('|')!=='1 Jakhal Pack Leader, 1 Dishonoured and 8 Jakhals|or:|1 Jakhal Pack Leader, 2 Dishonoured and 17 Jakhals')throw Error('Review Jakhal composition alternatives');
// Use the printed bounds for the common importer. Its exact two allowed
// compositions are cross-checked against the MFM export below.
const composition=tables.Datasheets_unit_composition.filter(c=>c.datasheet_id!==jakhals.id);
for(const [i,description] of ['1 Jakhal Pack Leader','1-2 Dishonoured','8-17 Jakhals'].entries())composition.push({...rows[0],line:String(i+1),description});
const clean={...tables,Datasheets_unit_composition:composition,Datasheets_keywords:tables.Datasheets_keywords.filter(k=>!empty.has(k))};
const sheets=importNativeMuster(clean,manual,{name:'World Eaters',slug:'world-eaters',factionId:'WE',packAircraftOrModels:[]});
const json=path=>JSON.parse(readFileSync(path,'utf8'));
applyModelComposition(sheets,json(unitsPath),json(compositionPath),manual.slug,manual.firstSeen);
if(sheets.length!==30||sheets.filter(s=>s.keywords.includes('BLOOD LEGIONS')).length!==5)throw Error('Reconcile World Eaters and conditional Blood Legions inventories');
const revision={pack:'https://assets.warhammer-community.com/eng_30-09_wh40k_faction_pack_world_eaters-rxxj1fzeoh-kfx1cectxb.pdf',packVersion:'1.3',manual:manual.version,exportUpdated:tables.Last_update[0].last_update,
 composition:'https://github.com/wn-mitch/40kdc-data/tree/fd1035a4e2ac7330835010e660bdd7216bfa3fd9/data/core/world-eaters'};
writeFileSync(destination,"// Generated by scripts/import-world-eaters.mjs.\nimport type {Datasheet2026} from './datasheets-2026';\n"+
 'export const WORLD_EATERS_REVISION='+JSON.stringify(revision)+' as const;\n'+
 'export const WORLD_EATERS_SHEETS:readonly Datasheet2026[]='+JSON.stringify(sheets,null,2)+';\n');
