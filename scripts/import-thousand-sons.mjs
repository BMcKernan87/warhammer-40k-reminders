import {readFileSync,writeFileSync} from 'node:fs';
import {parse} from 'yaml';
import {loadExport} from './import-wahapedia-11e.mjs';
import {importNativeMuster} from './import-native-muster.mjs';
import {applyModelComposition} from './import-mfm-composition.mjs';

const [directory,manualPath,unitsPath,compositionPath,destination]=process.argv.slice(2);
if(!destination)throw Error('Usage: node scripts/import-thousand-sons.mjs CSV_DIR MFM_YAML UNITS_JSON COMPOSITIONS_JSON OUTPUT_TS');
const {tables}=await loadExport({directory});
const manual=parse(readFileSync(manualPath,'utf8'));
const name='Thousand Sons',slug='thousand-sons';
if(manual.version!=='1.6'||manual.firstSeen!=='2026-10-14')throw Error('Review Thousand Sons MFM revision');
const natives=tables.Datasheets.filter(s=>s.faction_id==='TS'&&s.source_id==='000000027');
const empty=new Set(natives.flatMap(s=>{
 const keywords=tables.Datasheets_keywords.filter(k=>k.datasheet_id===s.id);
 const faction=keywords.filter(k=>k.is_faction_keyword==='true'&&k.keyword);
 if(faction.length!==1||![name,'Scintillating Legions'].includes(faction[0].keyword))throw Error('Review Thousand Sons faction keyword '+s.name);
 return keywords.filter(k=>k.is_faction_keyword==='true'&&!k.keyword&&!k.model);
}));
const sheets=importNativeMuster({...tables,Datasheets_keywords:tables.Datasheets_keywords.filter(k=>!empty.has(k))},manual,{name,slug,factionId:'TS',packAircraftOrModels:[],battleOnlyModels:{'Pink Horrors':['Blue Horrors','Brimstone Horrors'],'Blue Horrors':['Brimstone Horrors']}});
const json=path=>JSON.parse(readFileSync(path,'utf8'));
applyModelComposition(sheets,json(unitsPath),json(compositionPath),slug,manual.firstSeen);
if(sheets.length!==34||sheets.filter(s=>s.keywords.includes('SCINTILLATING LEGIONS')).length!==6)throw Error('Review Thousand Sons inventory');
// The August export already incorporates these profile changes. Keep them
// reconciled with the September matched-play pack when refreshing the export.
const byName=new Map(sheets.map(sheet=>[sheet.unit,sheet]));
for(const [unit,toughness] of Object.entries({'Scarab Occult Terminators':6,'Sorcerer In Terminator Armour':6,Ahriman:5,'Exalted Sorcerer':5,'Exalted Sorcerer on Disc of Tzeentch':5,'Infernal Master':5,'Rubric Marines':5,Sorcerer:5})){
 const s=byName.get(unit),profiles=s?.profile?[s.profile]:Object.values(s?.modelProfiles??{});
 if(!profiles.length||profiles.some(p=>p.toughness!==toughness))throw Error('Reconcile September Toughness on '+unit);
}
const drake=byName.get('Heldrake'),p=drake.profile;
if(!p||p.move!=='12"'||p.objectiveControl!==0||drake.keywords.includes('AIRCRAFT')||byName.get('Flamers').profile.leadership!=='7+'||
 byName.get('Chaos Vindicator').profile.move!=='9"'||['Chaos Rhino','Chaos Land Raider','Chaos Predator Annihilator','Chaos Predator Destructor','Chaos Vindicator'].some(unit=>!byName.get(unit).keywords.includes('FRAME')))throw Error('Reconcile September profile changes');
const revision={pack:'https://assets.warhammer-community.com/eng_30-09_wh40k_faction_pack_thousand_sons-4lioijwxdj-otjrinzt8c.pdf',packVersion:'1.3',manual:manual.version,exportUpdated:tables.Last_update[0].last_update,
 composition:'https://github.com/wn-mitch/40kdc-data/tree/fd1035a4e2ac7330835010e660bdd7216bfa3fd9/data/core/thousand-sons'};
const cabal=tables.Abilities.find(r=>r.faction_id==='TS'&&r.name==='Cabal of Sorcerers');
if(!cabal||!cabal.description.includes('Channel the Warp'))throw Error('Review current Cabal rule');
const casters={};
for(const card of natives){
 const printed=tables.Datasheets_abilities.find(a=>a.datasheet_id===card.id&&a.ability_id===cabal.id);
 if(!printed)continue;
 const restricted=printed.name.match(/Cabal of Sorcerers \((.+) only\)/i)?.[1];
 const model=restricted?tables.Datasheets_models.find(m=>m.datasheet_id===card.id&&m.name.toLowerCase()===restricted.toLowerCase()):undefined;
 if(restricted&&!model||printed.name&&!restricted)throw Error('Unrecognized Cabal bearer for '+card.name);
 casters[card.name]=model?.name??card.name;
}
if(Object.keys(casters).length!==12)throw Error('Review native Ritual caster inventory');
writeFileSync(destination,"// Generated by scripts/import-thousand-sons.mjs.\nimport type {Datasheet2026} from './datasheets-2026';\n"+
 'export const THOUSAND_SONS_REVISION='+JSON.stringify(revision)+' as const;\n'+
 'export const RITUAL_BEARERS:Readonly<Record<string,string>>='+JSON.stringify(casters,null,1)+';\n'+
 'export const THOUSAND_SONS_SHEETS:readonly Datasheet2026[]='+JSON.stringify(sheets,null,2)+';\n');
