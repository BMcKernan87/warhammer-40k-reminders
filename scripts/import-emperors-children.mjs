import {readFileSync,writeFileSync} from 'node:fs';
import {parse} from 'yaml';
import {loadExport} from './import-wahapedia-11e.mjs';
import {importNativeMuster} from './import-native-muster.mjs';
import {applyModelComposition} from './import-mfm-composition.mjs';

const [directory,manualPath,unitsPath,compositionPath,destination]=process.argv.slice(2);
if(!destination)throw Error('Usage: node scripts/import-emperors-children.mjs CSV_DIR MFM_YAML UNITS_JSON COMPOSITIONS_JSON OUTPUT_TS');
const {tables}=await loadExport({directory});
const manual=parse(readFileSync(manualPath,'utf8'));
const name='Emperor’s Children',slug='emperors-children';
if(manual.version!=='1.6'||manual.firstSeen!=='2026-10-14')throw Error('Review Emperor’s Children MFM revision');
const natives=tables.Datasheets.filter(s=>s.faction_id==='EC'&&s.source_id==='000000280');
const empty=new Set(natives.flatMap(s=>{
 const keywords=tables.Datasheets_keywords.filter(k=>k.datasheet_id===s.id);
 const faction=keywords.filter(k=>k.is_faction_keyword==='true'&&k.keyword);
 if(faction.length!==1||![name,'Legions of Excess'].includes(faction[0].keyword))throw Error('Review EC faction keyword '+s.name);
 return keywords.filter(k=>k.is_faction_keyword==='true'&&!k.keyword&&!k.model);
}));
const sheets=importNativeMuster({...tables,Datasheets_keywords:tables.Datasheets_keywords.filter(k=>!empty.has(k))},manual,{name,slug,factionId:'EC',urlSlug:'emperor-s-children',packAircraftOrModels:[]});
const json=path=>JSON.parse(readFileSync(path,'utf8'));
applyModelComposition(sheets,json(unitsPath),json(compositionPath),slug,manual.firstSeen);
if(sheets.length!==23||sheets.filter(s=>s.keywords.includes('LEGIONS OF EXCESS')).length!==5)throw Error('Review Emperor’s Children inventory');
// The August export already incorporates these profile changes. Keep them
// reconciled with the September matched-play pack when refreshing the export.
const byName=new Map(sheets.map(sheet=>[sheet.unit,sheet]));
for(const [unit,toughness] of Object.entries({'Chaos Terminators':6,'Lord Kakophonist':6,'Lucius the Eternal':6,Infractors:5,'Lord Exultant':5,Sorcerer:5,Tormentors:5})){
 if(byName.get(unit)?.profile?.toughness!==toughness)throw Error('Reconcile September Toughness on '+unit);
}
const drake=byName.get('Heldrake'),p=drake.profile;
if(!p||p.move!=='12"'||p.save!=='3+'||p.objectiveControl!==0||drake.keywords.includes('AIRCRAFT')||
 byName.get('Noise Marines').profile.wounds!==3||!byName.get('Fulgrim').keywords.includes('MOBILE')||
 ['Chaos Rhino','Chaos Land Raider'].some(unit=>!byName.get(unit).keywords.includes('FRAME')))throw Error('Reconcile September profile updates');
const revision={pack:'https://assets.warhammer-community.com/eng_30-09_wh40k_faction_pack_emperors_children-xp2mhzppxs-1cvykicdxu.pdf',packVersion:'1.3',manual:manual.version,exportUpdated:tables.Last_update[0].last_update,
 composition:'https://github.com/wn-mitch/40kdc-data/tree/fd1035a4e2ac7330835010e660bdd7216bfa3fd9/data/core/emperors-children'};
const thrill=tables.Abilities.find(a=>a.faction_id==='EC'&&a.name==='Thrill Seekers');
if(!thrill||!thrill.description.includes('Engagement Range')||!thrill.description.includes('this phase'))throw Error('Review Thrill Seekers targeting');
const enabled=natives.filter(card=>tables.Datasheets_abilities.some(a=>a.datasheet_id===card.id&&a.ability_id===thrill.id)).map(s=>s.name).sort();
if(enabled.length!==18)throw Error('Review the native Thrill Seekers recipients');
writeFileSync(destination,"// Generated by scripts/import-emperors-children.mjs.\nimport type {Datasheet2026} from './datasheets-2026';\n"+
 'export const EMPERORS_CHILDREN_REVISION='+JSON.stringify(revision)+' as const;\n'+
 'export const THRILL_SEEKERS:readonly string[]='+JSON.stringify(enabled)+';\n'+
 'export const EMPERORS_CHILDREN_SHEETS:readonly Datasheet2026[]='+JSON.stringify(sheets,null,2)+';\n');
