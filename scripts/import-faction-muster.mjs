import {readFileSync,writeFileSync} from 'node:fs';
import {parse} from 'yaml';
import {loadExport} from './import-wahapedia-11e.mjs';
import {importNativeMuster} from './import-native-muster.mjs';
import {applyModelComposition} from './import-mfm-composition.mjs';

export async function importFactionMuster(spec,args){
 const [directory,manualPath,unitsPath,compositionPath,destination]=args;
 const script='scripts/import-'+spec.slug+'.mjs';
 if(!destination)throw Error('Usage: node '+script+' CSV_DIR MFM_YAML UNITS_JSON COMPOSITIONS_JSON OUTPUT_TS');
 const {tables}=await loadExport({directory});
 const manual=parse(readFileSync(manualPath,'utf8'));
 if(manual.version!=='1.6'||manual.firstSeen!=='2026-10-14')throw Error('Review '+spec.name+' MFM revision');
 const canonical=record=>({...record,name:spec.manualNames?.[record.name.toLowerCase()]??record.name});
 manual.units=manual.units.map(canonical);
 const natives=tables.Datasheets.filter(s=>s.faction_id===spec.factionId&&(s.source_id===spec.sourceId||spec.packAircraftOrModels?.includes(s.name)));
 const empty=new Set(natives.flatMap(s=>{
  const keywords=tables.Datasheets_keywords.filter(k=>k.datasheet_id===s.id);
  const faction=keywords.filter(k=>k.is_faction_keyword==='true'&&k.keyword);
  if(faction.length!==1||![spec.name,spec.daemons].includes(faction[0].keyword))throw Error('Review '+spec.name+' faction keyword '+s.name);
  return keywords.filter(k=>k.is_faction_keyword==='true'&&!k.keyword&&!k.model);
 }));
 const sheets=importNativeMuster({...tables,Datasheets_keywords:tables.Datasheets_keywords.filter(k=>!empty.has(k))},manual,{...spec,packAircraftOrModels:spec.packAircraftOrModels??[]});
 const json=path=>JSON.parse(readFileSync(path,'utf8'));
 const compositions=json(compositionPath);
 applyModelComposition(sheets,json(unitsPath).map(canonical),spec.compositions?.(compositions)??compositions,spec.slug,manual.firstSeen);
 if(sheets.length!==spec.total||(spec.daemons&&sheets.filter(s=>s.keywords.includes(spec.daemons.toUpperCase())).length!==spec.daemonCount))throw Error('Review '+spec.name+' inventory');
 spec.reconcile(new Map(sheets.map(s=>[s.unit,s])));
 const revision={pack:'https://assets.warhammer-community.com/'+spec.pack,packVersion:spec.packVersion??'1.3',manual:manual.version,exportUpdated:tables.Last_update[0].last_update,
  composition:'https://github.com/wn-mitch/40kdc-data/tree/fd1035a4e2ac7330835010e660bdd7216bfa3fd9/data/core/'+spec.slug};
 writeFileSync(destination,"// Generated by "+script+".\nimport type {Datasheet2026} from './datasheets-2026';\n"+
  'export const '+spec.prefix+'_REVISION='+JSON.stringify(revision)+' as const;\n'+
  (spec.armyRuleExport?.(natives,tables)??'')+
  'export const '+spec.prefix+'_SHEETS:readonly Datasheet2026[]='+JSON.stringify(sheets,null,2)+';\n'+(spec.extraExport?.(natives,tables)??''));
}
