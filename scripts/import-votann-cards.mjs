import {writeFileSync} from 'node:fs';
import {loadExport} from './import-wahapedia-11e.mjs';

const [directory,destination]=process.argv.slice(2);
if(!destination)throw Error('Usage: node scripts/import-votann-cards.mjs CSV_DIR OUTPUT_TS');
const {tables}=await loadExport({directory});
const shared=new Map(tables.Abilities.map(a=>[a.id,a.name]));
const sources=new Map(tables.Source.map(s=>[s.id,s]));
const output=[];
for(const sheet of tables.Datasheets.filter(s=>s.faction_id==='LoV').sort((a,b)=>a.name.localeCompare(b.name,'en'))){
 const source=sources.get(sheet.source_id);
 if(source?.name.includes('Legends'))continue;
 if(source?.edition!=='11'||!sheet.link.startsWith('https://wahapedia.ru/wh40k11ed/factions/leagues-of-votann/'))throw Error('Wrong edition for '+sheet.name);
 const own=table=>tables[table].filter(r=>r.datasheet_id===sheet.id);
 const abilities=own('Datasheets_abilities'),profiles=own('Datasheets_models');
 const core=abilities.filter(a=>a.type==='Core').map(a=>[(a.name||shared.get(a.ability_id)),a.parameter].filter(Boolean).join(' '));
 const demise=core.find(a=>a.startsWith('Deadly Demise '))?.slice('Deadly Demise '.length)??null;
 if(!profiles.length||profiles.some(p=>p.inv_sv!==profiles[0].inv_sv||p.inv_sv_descr))throw Error('Inspect model-specific saves for '+sheet.name);
 const save=profiles[0].inv_sv==='-'?null:Number(profiles[0].inv_sv);
 const damage=sheet.damaged_w?sheet.damaged_w.match(/^1[-–](\d+)$/):null;
 if(sheet.damaged_w&&(!damage||!sheet.damaged_description.includes('subtract 1 from the Hit roll')))throw Error('Inspect damaged ability on '+sheet.name);
 const conversion=abilities.find(a=>a.name==='Conversion');
 const range=conversion?.description.match(/not within (\d+)"/i)?.[1];
 if(conversion&&!range)throw Error('Inspect Conversion range on '+sheet.name);
 const rows=own('Datasheets_wargear'),base=w=>w.name.trim().split(/\s+[–—-]\s+/)[0];
 const weapons=rows.map(row=>({name:row.name.trim(),phase:row.type==='Melee'?'Fight':'Shooting',
  abilities:row.description?row.description.split(/,\s*/):[],
  ...(rows.some(w=>w!==row&&w.type===row.type&&base(w)===base(row))?{mode:true}:{})}));
 output.push('  '+JSON.stringify(sheet.name)+': '+JSON.stringify({source:sheet.link,core,save,rangedSave:false,
  demise,damage:damage?{threshold:Number(damage[1]),oc:0}:null,conversion:range?Number(range):null,...(range&&!/successful/i.test(conversion.description)?{conversionRequiresHit:false}:{}),weapons}));
}
if(output.length!==22)throw Error('Unexpected Votann matched-play inventory');
writeFileSync(destination,"// Generated by scripts/import-votann-cards.mjs from the current 11e cards.\nimport type {KnightCardStats} from './knight-card-rules';\nexport const VOTANN_CARDS:Readonly<Record<string,KnightCardStats>>={\n"+output.join(',\n')+'\n};\n');
