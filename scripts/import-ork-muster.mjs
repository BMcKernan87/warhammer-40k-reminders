import {readFileSync,writeFileSync} from 'node:fs';
import {parse} from 'yaml';
import {loadExport} from './import-wahapedia-11e.mjs';
import {importNativeMuster,nativeNameKey} from './import-native-muster.mjs';

const [directory,manualFile,relationalUnits,relationalTiers,output]=process.argv.slice(2);
if(!output)throw Error('Usage: node scripts/import-ork-muster.mjs CSV_DIR ORKS_MFM_YAML UNITS_JSON COMPOSITIONS_JSON OUTPUT_TS');
const {tables}=await loadExport({directory});
const manual=parse(readFileSync(manualFile,'utf8'));
const spec={name:'Orks',slug:'orks',factionId:'ORK',packAircraftOrModels:['Gargantuan Squiggoth']};
const sheets=importNativeMuster(tables,manual,spec);
const ids=JSON.parse(readFileSync(relationalUnits,'utf8'));
const allTiers=new Map(JSON.parse(readFileSync(relationalTiers,'utf8')).map(row=>[row.unit_id,row]));
for(const sheet of sheets){
 const exact=ids.filter(row=>nativeNameKey(row.name)===nativeNameKey(sheet.unit));
 if(exact.length!==1||!exact[0].external_refs?.some(ref=>ref.namespace==='mfm'))throw Error(sheet.unit+' ambiguous or missing MFM model group');
 const groups=allTiers.get(exact[0].id);
 if(!groups?.tiers?.length||groups.faction_id!=='orks'||groups.game_version.edition!=='11th'||groups.game_version.dataslate!=='2026-10-14')throw Error(sheet.unit+' lacks an October composition tier');
 const variants={};
 for(const tier of groups.tiers){
  let combinations=[{}];
  for(const model of tier.models){
   if(!Number.isInteger(model.min)||!Number.isInteger(model.max)||model.max<model.min||model.min<0)throw Error(sheet.unit+' invalid model bounds');
   const next=[];
   for(const counts of combinations)for(let count=model.min;count<=model.max;count++)next.push({...counts,[model.name]:count});
   combinations=next;
  }
  for(const counts of combinations){
   const n=Object.values(counts).reduce((sum,value)=>sum+value,0);
   if(variants[n])throw Error(sheet.unit+' has more than one legal composition of '+n+' models');
   variants[n]=counts;
  }
 }
 const legal=Object.keys(variants).map(Number).sort((a,b)=>a-b);
 if(legal[0]!==sheet.sizes[0]||legal.at(-1)!==sheet.sizes.at(-1)||sheet.sizes.some(n=>!variants[n]))throw Error(sheet.unit+' mismatched starting strengths');
 sheet.compositionBySize=variants;
}
const revision={mfm:manual.version,exportUpdated:tables.Last_update[0].last_update,relationalMfm:'https://github.com/wn-mitch/40kdc-data/tree/fd1035a4e2ac7330835010e660bdd7216bfa3fd9/data/core/orks',forgeWorldPack:'https://assets.warhammer-community.com/eng_wh40k_faction_pack_orks-bk9eqvzbeq-rkrvgfwe8b.pdf'};
writeFileSync(output,"// Generated by scripts/import-ork-muster.mjs.\nimport type {Datasheet2026} from './datasheets-2026';\n"+
 'export const ORK_REVISION='+JSON.stringify(revision)+' as const;\n'+'export const ORK_SHEETS:readonly Datasheet2026[]='+JSON.stringify(sheets,null,2)+';\n');
