import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {isDeepStrictEqual} from 'node:util';
import {parse} from 'yaml';
import {loadExport,modelProfile,rosterMetadata} from './import-wahapedia-11e.mjs';
import {readPrices} from './import-imperial-knights.mjs';

const normal=name=>name.toLowerCase().replace(/[’‘]/g,"'").trim();
const requireMatch=(condition,detail)=>{if(!condition)throw Error('Daemonic Pact import: '+detail);};
const pack='https://assets.warhammer-community.com/eng_30-09_wh40k_faction_pack_chaos_daemons-e67vyzvv3x-mownb49uc3.pdf';
const mfm='https://mfm.warhammer-community.com/en/chaos-daemons';

export function importDaemonicPact(tables,manual){
 requireMatch(manual.slug==='chaos-daemons'&&manual.version,'unexpected MFM');
 const nativeSource=tables.Source.filter(s=>s.name==='Chaos Daemons'&&s.edition==='11'&&s.version);
 requireMatch(nativeSource.length===1,'missing or ambiguous 11th edition source');
 const native=tables.Datasheets.filter(d=>d.faction_id==='CD'&&d.source_id===nativeSource[0].id);
 const names=new Map(native.map(d=>[normal(d.name),d.name]));
 const priced=manual.units.filter(u=>!u.legends);
 const manualByName=new Map(priced.map(u=>[normal(u.name),u]));
 requireMatch(names.size===native.length&&manualByName.size===priced.length&&native.length===priced.length,'MFM and export inventories differ');
 const sheets=native.map(d=>{
  const price=manualByName.get(normal(d.name));
  requireMatch(price&&d.link.startsWith('https://wahapedia.ru/wh40k11ed/factions/chaos-daemons/'),d.name+' lacks a matching datasheet or price');
  const own=key=>tables[key].filter(s=>s.datasheet_id===d.id);
  const costs=readPrices(own('Datasheets_models_cost'),d.name,price);
  // Split allows new Horror types during a battle. They are never bought or
  // counted in the starting composition, even when they have their own profile.
  const splitModels=d.name==='Pink Horrors'?['Blue Horrors','Brimstone Horrors']:d.name==='Blue Horrors'?['Brimstone Horrors']:[];
  const data=rosterMetadata(tables,d.name,d.id,splitModels);
  requireMatch(data.keywords.includes('LEGIONES DAEMONICA'),d.name+' lacks the allied faction keyword');
  const min=data.composition.reduce((n,m)=>n+m.min,0),max=data.composition.reduce((n,m)=>n+m.max,0);
  requireMatch(costs.sizes[0]===min&&costs.sizes.at(-1)===max,d.name+' size and points bounds disagree');
  const models=own('Datasheets_models');
  requireMatch(models.length&&new Set(models.map(m=>m.name)).size===models.length,d.name+' missing or duplicate profiles');
  const profiles=models.length===1?{profile:modelProfile(models[0],d.name)}:{modelProfiles:Object.fromEntries(models.map(m=>[m.name,modelProfile(m,d.name)]))};
  const bodyIds=new Set(tables.Datasheets_leader.filter(l=>l.leader_id===d.id).map(l=>l.attached_id));
  const bodyguards=native.filter(b=>bodyIds.has(b.id)).map(b=>b.name).sort();
  const manualBodies=(price.supportTo??price.leaderTo??[]).map(b=>names.get(normal(b))).filter(Boolean).sort();
  requireMatch(isDeepStrictEqual(bodyguards,manualBodies)&&(d.is_support==='true')===!!price.supportTo,d.name+' attachment eligibility differs from MFM');
  const attachment=bodyguards.length?{attachmentRole:d.is_support==='true'?'support':'leader',bodyguards}:{};
  return {faction:'Chaos Knights',unit:d.name,source:d.link,pointsSource:mfm,verified:'sizes-and-points',...costs,...data,...profiles,...attachment};
 });
 return {pack,exportUpdated:tables.Last_update[0].last_update,mfmVersion:manual.version,sheets:sheets.sort((a,b)=>a.unit<b.unit?-1:1)};
}

