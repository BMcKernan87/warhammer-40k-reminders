it('applies conversion only on eligible weapon profiles and surfaces the Arkanyst charged test modifier',()=>{
 const thunder=s('Brôkhyr Thunderkyn'),fort=s('Hekaton Land Fortress'),evalr=s('Arkanyst Evaluator');
 let a=army(thunder,fort,evalr);
 expect(read(a).some(r=>r.summary.includes('Conversion (at more'))).toBe(false);
 a=kit(kit(a,thunder,'Squad weapons','SP conversion beamer'),fort,'Main gun','SP heavy conversion beamer');
 a=kit(a,fort,'Scanner or warhead','Hekaton warhead');
 const cards=read(a);
 const profile=(id:string,stage:string)=>cards.find(r=>r.title===id+' · Ranged weapon profiles'&&r.window===stage)?.summary;
 expect(profile(thunder.id,'Shooting')).toContain('12″, an unmodified 4+');
 expect(profile(fort.id,'Shooting')).toContain('a successful unmodified 4+');
 expect(profile(fort.id,'Movement')).not.toContain('Conversion (at more');
 expect(profile(fort.id,'Shooting')).toContain('One Shot');
 expect(profile(evalr.id,'Shooting')).toContain('subtract 2');
 expect(row(cards,'Panspectral Scanner','Shooting')).toBeUndefined();
 expect(row(cards,'Damaged','Shooting')?.summary).toContain('1–5');
 expect(row(cards,'Deadly Demise D6','Charge')?.units).toEqual([fort.id]);
});
