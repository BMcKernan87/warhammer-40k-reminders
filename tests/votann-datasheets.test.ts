 expect(row(cards,'Computational Mastermind','Command')).toMatchObject({timing:'end',turn:'own',summary:expect.stringContaining('for each objective')});
 expect(row(cards,'Resource Transmutation','Shooting')).toMatchObject({units:[ar.id,'Arkanyst Evaluator#2'],summary:expect.stringMatching(/spend 1 Yield Point.*up to 2 Yield Points/)});
 expect(row(cards,'Grim Efficiency','Command')?.summary).toMatch(/Once per battle round.*12″.*1CP/);
 expect(row(cards,'Ancestral Fortune','Fight')?.summary).toMatch(/Once per turn.*1 Yield Point.*unmodified 6/);
 expect(row(cards,'Predictive Guidance','Movement')).toMatchObject({turn:'opponent',timing:'end'});
 expect(row(cards,'Predictive Guidance','Charge')).toMatchObject({turn:'opponent'});
