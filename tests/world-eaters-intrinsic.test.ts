 let army=build(['Angron','Lord on Juggernaut','Bloodcrushers','Bloodletters','Khârn The Betrayer','Khorne Berzerkers','Chaos Land Raider','Chaos Rhino','Jakhals','Helbrute','Chaos Terminators','Skarbrand','Maulerfiend'],'Khorne Daemonkin','Strike Force');
