import {expect,it} from 'vitest';
import {addSelectionUnit,newSelection,type ArmySelection} from '../src/catalog';
import {rosterCost2026} from '../src/datasheets-2026';
import {knightLoadoutFor,setKnightGear} from '../src/knight-loadouts';
import {individualArmy,setInstanceAttachment} from '../src/roster-instances';
import {selectUpgrade2026} from '../src/upgrades-2026';
import {worldEatersIntrinsicReminders as cards} from '../src/world-eaters-intrinsic';
import {selectWorldEatersWarlord,worldEatersMusterFindings} from '../src/world-eaters-muster';

const id=(name:string)=>name+'#1';
function build(units:string[],detachment='Berzerker Warband',size:ArmySelection['battleSize2026']='Incursion'){
 let army=individualArmy({...newSelection('World Eaters'),battleSize2026:size,detachments2026:[detachment]});
 for(const unit of units)army=addSelectionUnit(army,unit);
 return army;
}
const join=(army:ArmySelection,leader:string,body:string)=>setInstanceAttachment(army,id(leader),id(body));
const find=(army:ArmySelection,name:string)=>cards(army).filter(r=>r.title===name);
it('generates the legal 1,000-point Khârn and Slaughterbound army with real Bodyguards, cargo and the correct retaliation timings',()=>{
 let army=build(['Khârn The Betrayer','Khorne Berzerkers','Chaos Rhino','Eightbound','Slaughterbound','Helbrute','Exalted Eightbound','Heldrake']);
 army=selectWorldEatersWarlord(army,id('Khârn The Betrayer'));
 army=join(join(army,'Khârn The Betrayer','Khorne Berzerkers'),'Slaughterbound','Eightbound');
 expect(rosterCost2026(army).total).toBe(1000);expect(worldEatersMusterFindings(army)).toEqual([]);
 const result=cards(JSON.parse(JSON.stringify(army)));
 expect(result.find(r=>r.title==='The Betrayer')).toMatchObject({window:'Charge',turn:'own',timing:'end',units:[id('Khârn The Betrayer'),id('Khorne Berzerkers')],summary:expect.stringMatching(/unengaged.*Bodyguard model/)});
 expect(result.filter(r=>r.title==='Berzerker Frenzy')).toHaveLength(5);
 expect(result.find(r=>r.title==='Legendary Killer')?.summary).toMatch(/Hit rolls of 1.*Wound rolls of 1/);
 expect(result.find(r=>r.title==='Murderous Charge')).toMatchObject({window:'Fight',units:[id('Khorne Berzerkers'),id('Khârn The Betrayer')],summary:expect.stringContaining('1 Strength')});
 expect(result.find(r=>r.title==='Blood Surge')).toMatchObject({window:'Shooting',turn:'opponent',summary:expect.stringMatching(/destroys a model.*D6\+2″.*not moved this phase.*closest enemy/)});
 expect(result.find(r=>r.title==='Rage Eternal')?.units).toEqual([id('Slaughterbound'),id('Eightbound')]);
 expect(result.find(r=>r.title==='Possessed Lord')?.units).toEqual([id('Slaughterbound')]);
 expect(result.find(r=>r.title==='Meet Any Challenge')?.units).toEqual([id('Chaos Rhino'),id('Khorne Berzerkers')]);
 expect(result.find(r=>r.title==='Frenzy')).toMatchObject({window:'Fight',turn:'either',summary:expect.stringMatching(/Once per turn.*fight next/)});
 expect(result.find(r=>r.title==='Rend and Tear')?.summary).toMatch(/Damage.*1.*Monster or Vehicle/);
 expect(result.find(r=>r.title==='Airborne Predator'&&r.window==='Fight')?.summary).toContain('can Fly');
 expect(new Set(result.map(r=>r.id)).size).toBe(result.length);
 const empty=build(['Khârn The Betrayer','Slaughterbound','Chaos Rhino']);
 expect(find(empty,'The Betrayer')).toEqual([]);expect(find(empty,'Legendary Killer')).toEqual([]);expect(find(empty,'Rage Eternal')).toEqual([]);
});
