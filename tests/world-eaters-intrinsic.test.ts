it('distinguishes a two-armed Helbrute from a shooting build and bearer-only daemonic wargear from formation effects',()=>{
 let army=build(['Helbrute','Bloodcrushers','Lord on Juggernaut','Flesh Hounds','Bloodletters'],'Khorne Daemonkin','Strike Force');
 const kit=knightLoadoutFor(army.faction,'Helbrute')!,slot=kit.slots[0];
 const arm=slot.choices.find(c=>c.items.length===2&&c.items.includes('Helbrute fist')&&c.items.includes('Helbrute hammer'))!;
 expect(find(army,'Devoted to Destruction')).toEqual([]);
 army=setKnightGear(army,id('Helbrute'),slot.name,arm.name);
 expect(find(army,'Devoted to Destruction')[0].summary).toMatch(/2 Attacks.*Helbrute fist.*Helbrute hammer/);
 const letterKit=knightLoadoutFor(army.faction,'Bloodletters')!;
 expect(find(army,'Daemonic Icon')).toEqual([]);expect(find(army,'Instrument of Chaos')).toEqual([]);
 army=setKnightGear(army,id('Bloodletters'),letterKit.slots[0].name,'Daemonic Icon');
 army=setKnightGear(army,id('Bloodletters'),letterKit.slots[1].name,'Instrument of Chaos');
 expect(find(army,'Daemonic Icon').every(r=>r.summary.includes('Leadership 6+')&&r.units?.every(x=>x===id('Bloodletters')))).toBe(true);
 expect(find(army,'Instrument of Chaos')[0]).toMatchObject({window:'Charge',units:[id('Bloodletters')]});
 army=join(selectUpgrade2026(army,id('Lord on Juggernaut'),'Disciple of Khorne'),'Lord on Juggernaut','Flesh Hounds');
 expect(find(army,'Hunters from the Warp')[0]).toMatchObject({window:'End of opponent turn',timing:'end',units:[id('Flesh Hounds'),id('Lord on Juggernaut')]});
 expect(find(army,'Collar of Khorne').every(r=>r.units?.length===1&&r.units[0]===id('Flesh Hounds')&&r.summary.includes('Psychic Attack'))).toBe(true);
});
