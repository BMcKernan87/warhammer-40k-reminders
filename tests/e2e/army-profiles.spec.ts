import {test,expect} from '@playwright/test';
test('mobile builder equipment choices persist across profiles without showing legacy reminders',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto('./');
 await page.getByLabel('Select unit').selectOption('Immortals');
 await page.getByRole('button',{name:'Add',exact:true}).click();
 await page.getByRole('button',{name:'Play reminders'}).click();
 await expect(page.getByText('11th-edition army setup')).toBeVisible();
 await page.getByRole('button',{name:'Edit army'}).click();
 await page.getByLabel('Equipment for Immortals').selectOption('Tesla carbine');
 await page.getByRole('button',{name:'Play reminders'}).click();
 await expect(page.getByRole('heading',{name:'Phase reminders'})).toBeVisible();
 await page.getByRole('button',{name:'Edit army'}).click();
 page.once('dialog',dialog=>dialog.accept('Orks army'));
 await page.getByRole('button',{name:'New army'}).click();
 await page.getByLabel('Army faction').selectOption('Orks');
 await page.getByLabel('Saved army').selectOption('default');
 await expect(page.getByLabel('Equipment for Immortals')).toHaveValue('Tesla carbine');
 await expect(page.getByLabel('Army faction')).toHaveValue('Necrons');
});
test('print contains all phases even when current phase is filtered',async({page})=>{
 await page.setViewportSize({width:375,height:812});
 await page.goto('./');
 await page.getByRole('button',{name:'Play reminders'}).click();

 const phases=page.locator('.print-sheet h3');
 await expect(phases).toHaveCount(11);
 await page.emulateMedia({media:'print'});
 await expect(page.locator('.print-sheet')).toBeVisible();
 await expect(page.locator('.print-sheet h3')).toContainText(['Pre-battle','Start of battle round','Start of turn','Command','Movement','Shooting','Charge','Fight','End of your turn','End of opponent turn','End of battle round']);
});

test('mobile Necron detachment changes preserve a saved draft, gear and checkmarks and regenerate only the new rules',async({page})=>{
 test.setTimeout(90000);
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setViewportSize({width:390,height:844});
 await page.goto('./');
 const check=(name:string)=>page.getByRole('checkbox',{name:new RegExp(name)});
 await check('Hand of the Dynasty').check();
 await check('Skyshroud Spearhead').check();
 for(const unit of ['Overlord','Immortals','Tomb Blades']){
  await page.getByLabel('Select unit',{exact:true}).selectOption(unit);
  await page.getByRole('button',{name:'Add',exact:true}).click();
 }
 await page.getByLabel('Attach squad Overlord#1',{exact:true}).selectOption('Immortals#1');
 await page.getByLabel('Equipment for Immortals',{exact:true}).selectOption('Tesla carbine');
 await page.getByLabel('11th upgrade for squad Immortals#1',{exact:true}).selectOption('Tools of Dominion');
 await page.getByLabel('11th upgrade for squad Tomb Blades#1',{exact:true}).selectOption('Recursive Reanimation');
 await page.getByRole('button',{name:'Play reminders',exact:true}).click();
 const sheet=page.getByRole('heading',{name:'Phase reminders',exact:true}).locator('..');
 const before=await page.evaluate(()=>JSON.parse(localStorage.getItem('w40k-reminders-profiles-v1')!).profiles[0]);
 await sheet.getByLabel('Show phase').selectOption('Command');
 await sheet.getByRole('checkbox',{name:/Reanimation Protocols · D3 wounds/}).check();
 const checked=await page.evaluate(()=>JSON.parse(localStorage.getItem('w40k-reminders-profiles-v1')!).profiles[0].completed);
 expect(checked.length).toBe(1);
 await page.getByRole('button',{name:'Edit army',exact:true}).click();
 await check('Hand of the Dynasty').uncheck();
 await expect(page.getByLabel('11th upgrade for squad Immortals#1',{exact:true})).toHaveCount(0);
 await expect(page.getByLabel('11th upgrade for squad Tomb Blades#1',{exact:true})).toHaveValue('Recursive Reanimation');
 await check('Skyshroud Spearhead').uncheck();
 await page.reload();
 await expect(page.getByLabel('Saved army',{exact:true})).toHaveValue(before.id);
 await expect(page.getByRole('status')).toHaveCount(0);
 await expect(page.getByLabel('Equipment for Immortals',{exact:true})).toHaveValue('Tesla carbine');
 await expect(page.getByLabel('Attach squad Overlord#1',{exact:true})).toHaveValue('Immortals#1');
 await expect(page.getByLabel('11th upgrade for squad Tomb Blades#1',{exact:true})).toHaveCount(0);
 const draft=await page.evaluate(()=>JSON.parse(localStorage.getItem('w40k-reminders-profiles-v1')!).profiles[0]);
 expect(draft.army.instances).toEqual(before.army.instances);
 expect(draft.army.detachments2026).toEqual([]);
 expect(draft.army.upgrades2026).toEqual({});
 expect(draft.completed).toEqual(checked);
 await check('Awakened Dynasty').check();
 await expect(check('Hand of the Dynasty')).toBeDisabled();
 await page.getByLabel('11th upgrade for squad Overlord#1',{exact:true}).selectOption('Veil of Darkness');
 await page.getByRole('button',{name:'Play reminders',exact:true}).click();
 await sheet.getByLabel('Show phase').selectOption('Command');
 await sheet.getByLabel('Show completed reminders').check();
 await expect(sheet.getByRole('checkbox',{name:/Reanimation Protocols · D3 wounds/})).toBeChecked();
 await sheet.getByLabel('Show phase').selectOption('Shooting');
 await expect(sheet.getByText('Command Protocols',{exact:true})).toBeVisible();
 await expect(sheet.getByText(/Tools of Dominion|Recursive Reanimation|Nanosaturation/)).toHaveCount(0);
 await page.emulateMedia({media:'print'});
 const printed=page.getByRole('region',{name:'Printable army reminders'});
 await expect(printed.getByText(/Veil of Darkness/).first()).toBeVisible();
 await expect(printed.getByText(/Tools of Dominion|Recursive Reanimation|Nanosaturation/)).toHaveCount(0);
 await expect(printed.locator('h3')).toHaveCount(11);
 expect(errors).toEqual([]);
});
